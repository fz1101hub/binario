package it.binario.app.plannedjourney

import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

object PlannedJourneyIcsContract {
    const val MAX_BYTES = 262_144
    const val MAX_EVENTS = 120
    private const val PRODUCT_ID = "-//Binario//Planned Journeys 1.0//IT"

    internal fun productId(): String = PRODUCT_ID
}

data class PlannedJourneyCalendarEvent(
    val uid: String,
    val journeyId: String,
    val occurrenceDate: LocalDate,
    val startsAt: Instant,
    val summary: String,
    val reminderMinutes: Int?
)

/**
 * Localized human-readable text for exported calendar descriptions. Calendar
 * property names, timestamps and metadata intentionally remain language-neutral.
 */
data class PlannedJourneyIcsText(
    val eventDescription: String,
    val reminderDescription: String
) {
    fun describe(segment: PlannedJourneySegment): String = eventDescription.format(
        segment.origin.displayName,
        segment.destination.displayName,
        segment.departure.date,
        segment.departure.time,
        segment.departure.timeZone.id
    )

    companion object {
        val ITALIAN = PlannedJourneyIcsText(
            eventDescription = "Viaggio: %s → %s, partenza %s alle %s (%s)",
            reminderDescription = "Promemoria viaggio Binario"
        )
    }
}

sealed interface PlannedJourneyIcsParseResult {
    data class Valid(val events: List<PlannedJourneyCalendarEvent>) : PlannedJourneyIcsParseResult
    data class Invalid(val detail: String) : PlannedJourneyIcsParseResult
}

/** RFC 5545 boundary for export and safe preview of calendars generated by Binario. */
object PlannedJourneyIcs {
    private val utcFormatter = DateTimeFormatter.ofPattern("yyyyMMdd'T'HHmmss'Z'").withZone(ZoneOffset.UTC)

    fun export(
        journeys: Iterable<PlannedJourney>,
        generatedAt: Instant,
        text: PlannedJourneyIcsText = PlannedJourneyIcsText.ITALIAN
    ): String {
        val events = journeys
            .filter { PlannedJourneyValidator.validate(it).isEmpty() }
            .flatMap { journey -> PlannedJourneyOccurrences.forJourney(journey).map { journey to it } }
            .sortedWith(compareBy<Pair<PlannedJourney, PlannedJourneyOccurrence>> { it.second.scheduledAt }.thenBy { it.first.id })
            .take(PlannedJourneyIcsContract.MAX_EVENTS)
        val logicalLines = buildList {
            add("BEGIN:VCALENDAR")
            add("VERSION:2.0")
            add("PRODID:${escapeText(PlannedJourneyIcsContract.productId())}")
            add("CALSCALE:GREGORIAN")
            add("METHOD:PUBLISH")
            events.forEach { (journey, occurrence) -> addAll(eventLines(journey, occurrence, generatedAt, text)) }
            add("END:VCALENDAR")
        }
        val calendar = logicalLines.flatMap(::foldUtf8Line).joinToString("\r\n", postfix = "\r\n")
        require(calendar.toByteArray(StandardCharsets.UTF_8).size <= PlannedJourneyIcsContract.MAX_BYTES) {
            "Calendar export exceeds ${PlannedJourneyIcsContract.MAX_BYTES} bytes"
        }
        return calendar
    }

    /**
     * Parses only the bounded metadata emitted by [export]. It is an import preview,
     * not a reconstruction of the full PlannedJourney JSON contract.
     */
    fun parseOwnedCalendar(calendar: String): PlannedJourneyIcsParseResult {
        if (calendar.toByteArray(StandardCharsets.UTF_8).size > PlannedJourneyIcsContract.MAX_BYTES) {
            return PlannedJourneyIcsParseResult.Invalid("Calendar exceeds the byte limit")
        }
        return runCatching {
            val lines = unfold(calendar)
            require(lines.firstOrNull() == "BEGIN:VCALENDAR" && lines.lastOrNull() == "END:VCALENDAR") {
                "Invalid calendar envelope"
            }
            require(lines.contains("PRODID:${escapeText(PlannedJourneyIcsContract.productId())}")) {
                "Calendar was not generated by Binario"
            }
            val events = mutableListOf<PlannedJourneyCalendarEvent>()
            var cursor = 0
            while (cursor < lines.size) {
                if (lines[cursor] != "BEGIN:VEVENT") {
                    cursor += 1
                    continue
                }
                val end = (cursor + 1 until lines.size).firstOrNull { index -> lines[index] == "END:VEVENT" } ?: -1
                require(end > cursor) { "Unclosed event" }
                events += parseEvent(lines.subList(cursor + 1, end))
                require(events.size <= PlannedJourneyIcsContract.MAX_EVENTS) { "Too many events" }
                cursor = end + 1
            }
            PlannedJourneyIcsParseResult.Valid(events)
        }.getOrElse { error -> PlannedJourneyIcsParseResult.Invalid(error.message ?: "Malformed calendar") }
    }

    private fun eventLines(
        journey: PlannedJourney,
        occurrence: PlannedJourneyOccurrence,
        generatedAt: Instant,
        text: PlannedJourneyIcsText
    ): List<String> {
        val first = occurrence.itinerary.segments.first()
        val last = occurrence.itinerary.segments.last()
        val summary = journey.label.ifBlank { "${first.origin.displayName} → ${last.destination.displayName}" }
        val description = occurrence.itinerary.segments.joinToString(separator = "\n", transform = text::describe)
        return buildList {
            add("BEGIN:VEVENT")
            add("UID:${uid(journey.id, occurrence.occurrenceDate)}")
            add("DTSTAMP:${utcFormatter.format(generatedAt)}")
            add("DTSTART:${utcFormatter.format(occurrence.scheduledAt)}")
            add("SUMMARY:${escapeText(summary)}")
            add("DESCRIPTION:${escapeText(description)}")
            add("X-BINARIO-JOURNEY-ID:${escapeText(journey.id)}")
            add("X-BINARIO-OCCURRENCE-DATE:${occurrence.occurrenceDate}")
            journey.reminder?.let { reminder ->
                add("BEGIN:VALARM")
                add("ACTION:DISPLAY")
                add("TRIGGER:-PT${reminder.minutesBeforeDeparture.minutes}M")
                add("DESCRIPTION:${escapeText(text.reminderDescription)}")
                add("END:VALARM")
            }
            add("END:VEVENT")
        }
    }

    private fun parseEvent(lines: List<String>): PlannedJourneyCalendarEvent {
        val uid = lines.requiredValue("UID")
        val journeyId = unescapeText(lines.requiredValue("X-BINARIO-JOURNEY-ID"))
        val occurrenceDate = LocalDate.parse(lines.requiredValue("X-BINARIO-OCCURRENCE-DATE"))
        val startsAt = Instant.from(utcFormatter.parse(lines.requiredValue("DTSTART")))
        val summary = unescapeText(lines.requiredValue("SUMMARY"))
        val reminder = lines.firstOrNull { it.startsWith("TRIGGER:-PT") && it.endsWith("M") }
            ?.removePrefix("TRIGGER:-PT")
            ?.removeSuffix("M")
            ?.toIntOrNull()
        require(uid == uid(journeyId, occurrenceDate)) { "Event UID does not match its Binario identity" }
        return PlannedJourneyCalendarEvent(uid, journeyId, occurrenceDate, startsAt, summary, reminder)
    }

    private fun uid(journeyId: String, occurrenceDate: LocalDate): String {
        val digest = MessageDigest.getInstance("SHA-256")
            .digest("$journeyId|$occurrenceDate".toByteArray(StandardCharsets.UTF_8))
            .take(16)
            .joinToString("") { byte -> "%02x".format(byte.toInt() and 0xff) }
        return "$digest@binario.local"
    }

    private fun escapeText(value: String): String = value
        .replace("\\", "\\\\")
        .replace("\r\n", "\n")
        .replace("\r", "\n")
        .replace("\n", "\\n")
        .replace(";", "\\;")
        .replace(",", "\\,")

    private fun unescapeText(value: String): String {
        val result = StringBuilder()
        var escaped = false
        value.forEach { character ->
            if (!escaped && character == '\\') {
                escaped = true
            } else if (escaped) {
                result.append(if (character == 'n' || character == 'N') '\n' else character)
                escaped = false
            } else {
                result.append(character)
            }
        }
        if (escaped) result.append('\\')
        return result.toString()
    }

    private fun foldUtf8Line(line: String): List<String> {
        val physical = mutableListOf<String>()
        var current = StringBuilder()
        var currentBytes = 0
        line.codePoints().forEach { codePoint ->
            val text = String(Character.toChars(codePoint))
            val bytes = text.toByteArray(StandardCharsets.UTF_8).size
            if (currentBytes + bytes > 75) {
                physical += current.toString()
                current = StringBuilder(" ").append(text)
                currentBytes = 1 + bytes
            } else {
                current.append(text)
                currentBytes += bytes
            }
        }
        physical += current.toString()
        return physical
    }

    private fun unfold(calendar: String): List<String> {
        val physical = calendar.replace("\r\n", "\n").replace('\r', '\n').split('\n')
        val logical = mutableListOf<String>()
        physical.filter { it.isNotEmpty() }.forEach { line ->
            require(line.toByteArray(StandardCharsets.UTF_8).size <= 75) { "Physical line exceeds 75 octets" }
            if (line.startsWith(' ') || line.startsWith('\t')) {
                require(logical.isNotEmpty()) { "Invalid folded line" }
                logical[logical.lastIndex] = logical.last() + line.drop(1)
            } else {
                logical += line
            }
        }
        return logical
    }

    private fun List<String>.requiredValue(name: String): String =
        firstOrNull { it.startsWith("$name:") }?.substringAfter(':')
            ?: throw IllegalArgumentException("Missing $name")
}
