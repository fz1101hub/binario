#!/usr/bin/env python3
"""
gen_r.py -- emit compile-only R.kt and BuildConfig.kt for an Android module without aapt/AGP.

  python3 -I gen_r.py --repo <checkout> --module app|wear --out <dir>

R.kt    : object R { object string { const val name: Int = ... } ... } for every resource type found
          under <module>/src/main/res (values*/ element names, file based resource dirs, @+id/ ids).
          Ids are unique per (type, name): 0x7f000000 | typeIndex << 16 | entry, like aapt's layout.
BuildConfig.kt : only when the module enables buildFeatures.buildConfig; DEBUG, APPLICATION_ID,
          BUILD_TYPE, VERSION_CODE, VERSION_NAME (gradle.properties via the providers chain in the
          build file) and every buildConfigField(...) of the build file.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

TYPE_ORDER = ["anim", "animator", "array", "attr", "bool", "color", "dimen", "drawable", "font", "id",
              "integer", "interpolator", "layout", "menu", "mipmap", "plurals", "raw", "string", "style",
              "styleable", "transition", "xml"]
VALUE_ELEMENTS = {"string": "string", "plurals": "plurals", "color": "color", "style": "style", "dimen": "dimen",
                  "integer": "integer", "bool": "bool", "string-array": "array", "integer-array": "array",
                  "array": "array", "attr": "attr", "declare-styleable": "styleable", "fraction": "fraction"}
FILE_DIRS = {"drawable", "mipmap", "layout", "xml", "raw", "font", "anim", "animator", "menu", "color",
             "interpolator", "transition"}


def res_name(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def scan_res(res_dir):
    found = {}  # type -> set(names)

    def add(t, n):
        found.setdefault(t, set()).add(res_name(n))

    id_re = re.compile(r'@\+id/([A-Za-z0-9_.]+)')
    for d in sorted(Path(res_dir).iterdir()):
        if not d.is_dir():
            continue
        base = d.name.split("-")[0]
        for f in sorted(d.iterdir()):
            if not f.is_file():
                continue
            if base == "values":
                try:
                    root = ET.parse(f).getroot()
                except ET.ParseError as e:
                    sys.exit(f"{f}: {e}")
                for el in root:
                    tag = el.tag
                    name = el.get("name")
                    if name is None:
                        continue
                    if tag == "item":
                        t = el.get("type")
                        if t:
                            add(t, name)
                        continue
                    t = VALUE_ELEMENTS.get(tag)
                    if t:
                        add(t, name)
                    if tag == "declare-styleable":
                        for attr in el.findall("attr"):
                            if attr.get("name") and not attr.get("name").startswith("android:"):
                                add("attr", attr.get("name"))
            elif base in FILE_DIRS:
                stem = f.name.split(".")[0]
                add(base, stem)
            if f.suffix == ".xml":
                for m in id_re.finditer(f.read_text(encoding="utf-8", errors="replace")):
                    add("id", m.group(1))
    return found


def emit_r(namespace, found):
    lines = ["// Generated by gen_r.py (harness only; aapt is not available). Values are stable per run.",
             f"package {namespace}", "", "@Suppress(\"ClassName\", \"unused\")", "object R {"]
    types = sorted(found, key=lambda t: (TYPE_ORDER.index(t) if t in TYPE_ORDER else 99, t))
    for t in types:
        if t == "styleable":
            continue
        idx = TYPE_ORDER.index(t) + 1 if t in TYPE_ORDER else 0x40
        lines.append(f"    object {t} {{")
        for i, name in enumerate(sorted(found[t])):
            lines.append(f"        const val {name}: Int = 0x{0x7f000000 | (idx << 16) | (i + 1):08x}")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gradle_properties(repo):
    props = {}
    p = Path(repo) / "gradle.properties"
    if p.exists():
        for line in p.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                props[k.strip()] = v.strip()
    return props


def resolve_provider_chain(expr, props):
    """providers.gradleProperty("A").orElse(providers.gradleProperty("B")).orElse("x") -> first defined."""
    for m in re.finditer(r'gradleProperty\("([^"]+)"\)|orElse\("([^"]*)"\)', expr):
        if m.group(1) is not None:
            if m.group(1) in props:
                return props[m.group(1)]
        else:
            return m.group(2)
    return None


def emit_buildconfig(repo, module, build_text, namespace, props):
    def val_of(ident):
        m = re.search(r'\bval\s+%s\s*=\s*([^\n]+(?:\n\s+\.[^\n]+)*)' % re.escape(ident), build_text)
        return resolve_provider_chain(m.group(1), props) if m else None

    app_id = re.search(r'applicationId\s*=\s*"([^"]+)"', build_text)
    app_id = app_id.group(1) if app_id else namespace
    vc = re.search(r'versionCode\s*=\s*(\w+)', build_text)
    vn = re.search(r'versionName\s*=\s*(\w+)', build_text)
    version_code = val_of(vc.group(1)) if vc else None
    version_name = val_of(vn.group(1)) if vn else None
    fields = [("Boolean", "DEBUG", "true"), ("String", "APPLICATION_ID", f'"{app_id}"'),
              ("String", "BUILD_TYPE", '"debug"'), ("Int", "VERSION_CODE", str(int(version_code or 1))),
              ("String", "VERSION_NAME", f'"{version_name or "0"}"')]
    kinds = {"boolean": "Boolean", "String": "String", "int": "Int", "long": "Long", "float": "Float"}

    def block_spans(pattern):
        """[(name, start, end)] of `getByName("x") {...}` / `create("x") {...}` blocks (brace matched)."""
        spans = []
        for m in re.finditer(pattern, build_text):
            depth, i = 0, m.end() - 1
            while i < len(build_text):
                if build_text[i] == "{":
                    depth += 1
                elif build_text[i] == "}":
                    depth -= 1
                    if depth == 0:
                        break
                i += 1
            spans.append((m.group(1), m.start(), i))
        return spans

    type_blocks = block_spans(r'(?:getByName|create|maybeCreate)\("(\w+)"\)\s*\{')

    def build_type_of(pos):
        inner = [b for b in type_blocks if b[1] <= pos <= b[2]]
        return min(inner, key=lambda b: b[2] - b[1])[0] if inner else None

    def third_argument(start):
        """text of the third buildConfigField argument with balanced parentheses"""
        depth, i, buf = 0, start, []
        while i < len(build_text):
            c = build_text[i]
            if c == "(":
                depth += 1
            elif c == ")":
                if depth == 0:
                    break
                depth -= 1
            buf.append(c)
            i += 1
        return "".join(buf).strip()

    def resolve(value):
        value = value.strip()
        if value.startswith('"') and value.endswith('"') and value.count('"') == 2:
            return value[1:-1]  # Gradle passes the raw Java expression text
        if "gradleProperty(" in value or "orElse(" in value:
            return resolve_provider_chain(value, props)
        return val_of(value)

    # unit tests run the debug variant: debug build-type fields override defaultConfig; other build types are ignored
    collected = {}
    for m in re.finditer(r'buildConfigField\(\s*"(\w+)"\s*,\s*"(\w+)"\s*,\s*', build_text):
        kind, name = m.group(1), m.group(2)
        build_type = build_type_of(m.start())
        if build_type not in (None, "debug", "defaultConfig"):
            continue
        literal = resolve(third_argument(m.end()))
        if literal is None:
            literal = "false" if kind == "boolean" else '""'
        if kind == "String" and not literal.startswith('"'):
            literal = f'"{literal}"'
        if kind == "long" and not literal.endswith("L"):
            literal += "L"
        if name in collected and build_type != "debug":
            continue  # keep the debug value already recorded
        collected[name] = (kinds.get(kind, kind), name, literal)
    fields = [f for f in fields if f[1] not in collected] + list(collected.values())
    lines = ["// Generated by gen_r.py (harness only; mirrors AGP's debug BuildConfig).", f"package {namespace}", "",
             "object BuildConfig {"]
    for kind, name, literal in fields:
        lines.append(f"    const val {name}: {kind} = {literal}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--module", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    repo = Path(args.repo)
    build_file = repo / args.module / "build.gradle.kts"
    build_text = re.sub(r"//.*", "", build_file.read_text())
    ns = re.search(r'namespace\s*=\s*"([^"]+)"', build_text)
    if not ns:
        sys.exit(f"no namespace in {build_file}")
    namespace = ns.group(1)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    found = scan_res(repo / args.module / "src" / "main" / "res")
    (out / "R.kt").write_text(emit_r(namespace, found))
    summary = ", ".join(f"{t}={len(found[t])}" for t in sorted(found))
    if re.search(r'buildConfig\s*=\s*true', build_text):
        (out / "BuildConfig.kt").write_text(emit_buildconfig(repo, args.module, build_text, namespace, gradle_properties(repo)))
        summary += ", BuildConfig"
    else:
        bc = out / "BuildConfig.kt"
        if bc.exists():
            bc.unlink()
    print(f"gen_r {args.module} ({namespace}): {summary}")


if __name__ == "__main__":
    main()
