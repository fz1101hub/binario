#!/usr/bin/env python3
"""Generate the Android credits of every offline timetable pack from the GTFS manifests.

Settings › Info names, for each pack the build includes, its licensor, its licence and the page that publishes the
data (CC BY 4.0 §3(a), IODL 2.0 and the platforms' attribution rules).  The licensor and licence come from the
manifest fields ``attribution``, ``licence`` and ``licenceEvidence`` that ``tools/verify_embedded_assets.py``
requires for every pack (audit A7-03, proposal P3); this tool writes them to
``app/src/main/java/it/binario/app/data/gtfs/GtfsPackCredits.kt``, which the About screen reads.  A licence still
marked "da confermare dal titolare" is left out of the line (the licensor and the source page stay).

    python3 tools/build_android_gtfs_credits.py          # rewrite the Kotlin file
    python3 tools/build_android_gtfs_credits.py --check  # exit 1 when it is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

ROOT = Path(__file__).resolve().parents[1]
MANIFESTS = (
    Path("app/src/main/assets/gtfs/manifest.json"),
    Path("app/src/main/assets/gtfs-transit/manifest.json"),
    Path("app/src/personal/assets/gtfs-personal/manifest.json"),
)
OUTPUT = Path("app/src/main/java/it/binario/app/data/gtfs/GtfsPackCredits.kt")
OWNER_TO_CONFIRM = "da confermare dal titolare"


def credit_text(attribution: str, licence: str | None) -> str:
    """The licensor and licence on one line, without repeating a licence the attribution already names."""
    attribution = " ".join(attribution.split())
    if not licence or OWNER_TO_CONFIRM in licence.lower():
        return attribution
    licence = " ".join(licence.split())
    if licence in attribution:
        return attribution
    for separator in (" — ", " - "):
        head, found, tail = attribution.rpartition(separator)
        # "… — CC0" with licence "CC0 1.0": the attribution's short form becomes the full licence name.
        if found and tail and licence.startswith(tail):
            return f"{head}{separator}{licence}"
    return f"{attribution} — {licence}"


def kotlin_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    if any(ord(character) < 0x20 for character in escaped):
        raise ValueError(f"carattere di controllo in un credito: {value!r}")
    return f'"{escaped}"'


def credits(manifests: Sequence[Mapping[str, Any]]) -> list[tuple[str, str]]:
    """(sourceId, credit text) of every pack, in manifest order; a pack listed twice keeps its first entry."""
    rows: dict[str, str] = {}
    for manifest in manifests:
        for pack in manifest.get("packs", []):
            source_id = pack["sourceId"]
            attribution = pack.get("attribution")
            if not isinstance(attribution, str) or not attribution.strip():
                raise ValueError(f"{source_id}: attribution mancante nel manifest")
            licence = pack.get("licence")
            rows.setdefault(source_id, credit_text(attribution, licence if isinstance(licence, str) else None))
    return list(rows.items())


def render(manifests: Sequence[Mapping[str, Any]]) -> str:
    entries = "\n".join(
        f"        GtfsPackCredit({kotlin_string(source_id)}, {kotlin_string(text)})," for source_id, text in credits(manifests)
    )
    return f'''// Generated by tools/build_android_gtfs_credits.py from the GTFS manifests (attribution, licence): do not edit.
// tests/test_build_android_gtfs_credits.py fails when it no longer matches the manifests.
package it.binario.app.data.gtfs

import it.binario.app.data.core.SourceId
import it.binario.app.data.sources.RailSourceCatalog

/** Licensor and licence of one offline timetable pack, as its manifest entry records them. */
data class GtfsPackCredit(val sourceId: String, val text: String)

/** The Settings › Info credits of every timetable pack in this build: licensor, licence and the page of the data. */
object GtfsPackCredits {{
    /** Credited by their own strings (dataset, conversion and licence links): settings_credits_trenitalia/italo. */
    private val dedicated = setOf("trenitalia-gtfs", "italo-gtfs")

    val all: List<GtfsPackCredit> = listOf(
{entries}
    )

    /** One line per pack of [packs] (default: this build), in pack order: "source: licensor — licence. page". */
    fun lines(
        packs: List<EmbeddedGtfsPack> = EmbeddedGtfsPacks.forBuild(EmbeddedGtfsPacks.personalSourcesIncluded)
    ): List<String> {{
        val byId = all.associateBy(GtfsPackCredit::sourceId)
        return packs.map {{ it.sourceId.value }}.distinct().filterNot(dedicated::contains).mapNotNull {{ id ->
            byId[id]?.let {{ credit ->
                val source = RailSourceCatalog.byId(SourceId(id))
                "${{source?.displayName ?: id}}: ${{credit.text}}." + (source?.landingPage?.let {{ " $it" }} ?: "")
            }}
        }}
    }}
}}
'''


def load_manifests(root: Path, overrides: Mapping[str, Mapping[str, Any]] | None = None) -> list[Mapping[str, Any]]:
    """The manifests under ``root``; ``overrides`` (keyed by directory name) replaces a manifest not yet written."""
    manifests: list[Mapping[str, Any]] = []
    for relative in MANIFESTS:
        name = relative.parent.name
        if overrides and name in overrides:
            manifests.append(overrides[name])
        elif (root / relative).is_file():
            manifests.append(json.loads((root / relative).read_text(encoding="utf-8")))
    return manifests


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="non scrive: esce con 1 se il file Kotlin non è aggiornato")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    text = render(load_manifests(args.root))
    target = args.root / OUTPUT
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if args.check:
        if current != text:
            print(f"{OUTPUT} non corrisponde ai manifest: eseguire python3 tools/build_android_gtfs_credits.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT}: aggiornato")
        return 0
    if current != text:
        target.write_text(text, encoding="utf-8")
        print(f"Aggiornato: {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
