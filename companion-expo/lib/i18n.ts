const dictionaries: Record<CompanionLocale, Dictionary> = { it, en, de, fr, es };

/** Resolve BCP-47 preferences in order, retaining Italian for unknown or malformed input. */
export function resolveCompanionLocale(input?: string | readonly string[] | null): CompanionLocale {
  const preferences = Array.isArray(input) ? input : [input];
  for (const preference of preferences) {
    if (typeof preference !== "string") continue;
    const normalized = preference.trim().replace(/_/g, "-");
    if (!normalized) continue;
    try {
      const language = new Intl.Locale(normalized).language.toLowerCase();
      if ((supportedLocales as readonly string[]).includes(language)) return language as CompanionLocale;
    } catch {
      // Ignore malformed preferences and continue to the next BCP-47 candidate.
    }
  }
  return "it";
}

export function deviceCompanionLocale(): CompanionLocale {
  try {
    const nativePreferences = getLocales().map((locale) => locale.languageTag);
    if (nativePreferences.length > 0) return resolveCompanionLocale(nativePreferences);
  } catch {
    // Unit tests and non-Expo runtimes may not expose the native localization module.
  }
  const webPreferences = typeof navigator !== "undefined"
    ? navigator.languages?.length ? navigator.languages : [navigator.language]
    : undefined;
  return resolveCompanionLocale(webPreferences);
}

function interpolate(template: string, values: InterpolationValues): string {
  const plural = /\{(\w+),\s*plural,\s*one\s*\{([^{}]*)\}\s*other\s*\{([^{}]*)\}\}/g;
  const withPlural = template.replace(plural, (_match, key: string, one: string, other: string) => Number(values[key]) === 1 ? one : other);
  return withPlural.replace(/\{(\w+)\}/g, (_match, key: string) => values[key] === undefined ? "{" + key + "}" : String(values[key]));
}

export function translate(locale: CompanionLocale, key: TranslationKey, values: InterpolationValues = {}): string {
  return interpolate(dictionaries[locale]?.[key] ?? it[key], values);
}

export function createTranslator(locale: CompanionLocale = "it") {
  return <K extends TranslationKey>(key: K, values?: InterpolationValues) => translate(locale, key, values);
}

/** Device-locale changes recreate the Expo JS runtime. */
export function useTranslation() {
  const nativeLocales = useLocales();
  const locale = resolveCompanionLocale(
    nativeLocales.map((preference) => preference.languageTag),
  );
  return useMemo(() => ({ locale, t: createTranslator(locale) }), [locale]);
}

export function dictionaryKeys(locale: CompanionLocale): readonly TranslationKey[] {
  return Object.keys(dictionaries[locale]) as TranslationKey[];
}

export const translationDictionaries = dictionaries;
